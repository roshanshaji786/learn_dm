export type TKey = Key

export function useT() {
  const lang = useStore((s) => s.lang)
  return (k: Key, vars?: Record<string, string>) => {
    let s = (lang === 'ml' && ml[k]) || en[k]
    if (vars) for (const [a, b] of Object.entries(vars)) s = s.replace(`{${a}}`, b)
    return s
  }
}
