// Receipt and certificate PDFs, built in the browser with pdf-lib (loaded only when needed).
import { dayYear } from './format'

type Rgb = ReturnType<typeof import('pdf-lib').rgb>

// Standard PDF fonts only cover Latin text, so other characters are dropped.
const safe = (s: string) => s.replace(/₹/g, 'Rs. ').replace(/[^\x20-\x7E -ÿ]/g, '').replace(/\s+/g, ' ').trim()
const rs = (n: number) => 'Rs. ' + Number(n).toLocaleString('en-IN', { maximumFractionDigits: 2 })

function save(bytes: Uint8Array, name: string) {
  const blob = new Blob([bytes as BlobPart], { type: 'application/pdf' })
  const a = document.createElement('a')
  a.href = URL.createObjectURL(blob)
  a.download = name
  a.click()
  setTimeout(() => URL.revokeObjectURL(a.href), 4000)
}

async function logo() {
  try {
    const r = await fetch('/icons/icon-192.png')
    return new Uint8Array(await r.arrayBuffer())
  } catch {
    return null
  }
}

export type ReceiptData = {
  academy: string
  receiptNo: string
  paidOn: string
  student: string
  phone: string | null
  email: string
  course: string
  amount: number
  method: string
  reference: string | null
  totalFee: number
  paidToDate: number
  balance: number
}

export async function receiptPdf(d: ReceiptData) {
  const { PDFDocument, StandardFonts, rgb } = await import('pdf-lib')
  const doc = await PDFDocument.create()
  doc.setTitle(`Receipt ${d.receiptNo}`)
  const page = doc.addPage([595, 842])
  const f = await doc.embedFont(StandardFonts.Helvetica)
  const b = await doc.embedFont(StandardFonts.HelveticaBold)
  const brand = rgb(0.427, 0.157, 0.851)
  const ink = rgb(0.09, 0.07, 0.17)
  const mut = rgb(0.36, 0.34, 0.46)
  const W = 595
  page.drawRectangle({ x: 0, y: 742, width: W, height: 100, color: rgb(0.06, 0.04, 0.12) })
  const png = await logo()
  if (png) {
    const img = await doc.embedPng(png)
    page.drawImage(img, { x: 40, y: 762, width: 56, height: 56 })
  }
  page.drawText(safe(d.academy), { x: 110, y: 798, size: 20, font: b, color: rgb(1, 1, 1) })
  page.drawText('learn with Roshan Shaji  ·  WhatsApp +91 70120 45854', { x: 110, y: 778, size: 10, font: f, color: rgb(0.8, 0.75, 1) })
  page.drawText('PAYMENT RECEIPT', { x: 40, y: 700, size: 13, font: b, color: brand })
  page.drawText(d.receiptNo, { x: W - 40 - b.widthOfTextAtSize(d.receiptNo, 13), y: 700, size: 13, font: b, color: ink })

  let y = 660
  const row = (k: string, v: string, bold = false, color: Rgb = ink) => {
    page.drawText(k, { x: 40, y, size: 11, font: f, color: mut })
    const vv = safe(v)
    const font = bold ? b : f
    page.drawText(vv, { x: W - 40 - font.widthOfTextAtSize(vv, 12), y, size: 12, font, color })
    y -= 26
  }
  row('Date paid', dayYear(d.paidOn))
  row('Received from', d.student, true)
  if (d.phone) row('Phone', d.phone)
  row('Email', d.email)
  row('Course', d.course)
  row('Payment method', d.method + (d.reference ? `  (ref ${d.reference})` : ''))
  y -= 6
  page.drawRectangle({ x: 40, y: y - 18, width: W - 80, height: 52, color: rgb(0.965, 0.953, 1) })
  page.drawText('Amount received', { x: 56, y: y + 2, size: 12, font: b, color: ink })
  const amt = rs(d.amount)
  page.drawText(amt, { x: W - 56 - b.widthOfTextAtSize(amt, 22), y: y - 2, size: 22, font: b, color: brand })
  y -= 70
  row('Total course fee', rs(d.totalFee))
  row('Paid to date', rs(d.paidToDate))
  row('Balance', rs(d.balance), true, d.balance > 0 ? rgb(0.7, 0.33, 0.03) : rgb(0.02, 0.47, 0.34))
  page.drawLine({ start: { x: 40, y: 150 }, end: { x: W - 40, y: 150 }, thickness: 0.6, color: rgb(0.9, 0.88, 0.95) })
  page.drawText('This receipt was generated by the Darts AI Academy learning app and is valid without a signature.', { x: 40, y: 128, size: 9, font: f, color: mut })
  page.drawText('Questions about a payment? WhatsApp +91 70120 45854.', { x: 40, y: 114, size: 9, font: f, color: mut })
  save(await doc.save(), `${d.receiptNo}.pdf`)
}

export type CertData = { name: string; course: string; code: string; issuedAt: string; verifyUrl: string }

export async function certificatePdf(d: CertData) {
  const { PDFDocument, StandardFonts, rgb } = await import('pdf-lib')
  const doc = await PDFDocument.create()
  doc.setTitle(`Certificate ${d.code}`)
  const W = 842
  const H = 595
  const page = doc.addPage([W, H])
  const f = await doc.embedFont(StandardFonts.Helvetica)
  const b = await doc.embedFont(StandardFonts.HelveticaBold)
  const serif = await doc.embedFont(StandardFonts.TimesRomanBoldItalic)
  const brand = rgb(0.427, 0.157, 0.851)
  const ink = rgb(0.09, 0.07, 0.17)
  const mut = rgb(0.36, 0.34, 0.46)
  page.drawRectangle({ x: 0, y: 0, width: W, height: H, color: rgb(0.99, 0.985, 1) })
  page.drawRectangle({ x: 22, y: 22, width: W - 44, height: H - 44, borderColor: brand, borderWidth: 3 })
  page.drawRectangle({ x: 32, y: 32, width: W - 64, height: H - 64, borderColor: rgb(0.8, 0.74, 0.98), borderWidth: 1 })
  const center = (t: string, y: number, size: number, font = f, color: Rgb = ink) => {
    const s = safe(t)
    page.drawText(s, { x: (W - font.widthOfTextAtSize(s, size)) / 2, y, size, font, color })
  }
  const png = await logo()
  if (png) {
    const img = await doc.embedPng(png)
    page.drawImage(img, { x: (W - 64) / 2, y: 470, width: 64, height: 64 })
  }
  center('DARTS AI ACADEMY', 446, 14, b, brand)
  center('Certificate of Completion', 396, 34, serif, ink)
  center('This certifies that', 352, 13, f, mut)
  center(d.name, 304, 36, b, ink)
  center('has successfully completed the course', 266, 13, f, mut)
  center(d.course, 232, 22, b, brand)
  center(`Issued ${dayYear(d.issuedAt)}`, 200, 12, f, mut)
  page.drawLine({ start: { x: 96, y: 130 }, end: { x: 300, y: 130 }, thickness: 0.8, color: ink })
  page.drawText('Roshan Shaji', { x: 96, y: 112, size: 13, font: b, color: ink })
  page.drawText('Trainer, Darts AI Academy', { x: 96, y: 96, size: 10, font: f, color: mut })
  const idT = `Certificate ID: ${d.code}`
  page.drawText(idT, { x: W - 96 - b.widthOfTextAtSize(idT, 12), y: 112, size: 12, font: b, color: ink })
  const vT = `Verify at ${d.verifyUrl}`
  page.drawText(vT, { x: W - 96 - f.widthOfTextAtSize(vT, 10), y: 96, size: 10, font: f, color: mut })
  save(await doc.save(), `Certificate-${d.code}.pdf`)
}
